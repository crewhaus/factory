/**
 * Writes `src/builtin/worker-source.ts`: the builtin checker bundled into one
 * script, as text, for the runner's Blob worker (`src/builtin/runner.ts` says
 * why it must be text). Run it from anywhere after changing
 * `src/builtin/worker.ts` or any module it imports:
 *
 *   bun run scripts/gen-worker-source.ts           # rewrite the file
 *   bun run scripts/gen-worker-source.ts --check   # exit 1 when it is stale
 *
 * `src/builtin/worker-source.test.ts` runs `--check`, so a checker change
 * without a regeneration fails the tests, and so does a hand edit of the
 * text: what the worker runs is always what the source says. `--check`
 * compares the string itself, not the file's layout, which is biome's. The
 * bundle is whitespace-minified only (names and syntax kept), which also
 * drops the per-module path comments a readable bundle would carry, so the
 * text does not depend on where the script runs. Run it with the bun CI
 * pins: another version may print the same code differently.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const packageDir = join(import.meta.dir, "..");
const repoRoot = join(packageDir, "..", "..");
const entry = join(packageDir, "src", "builtin", "worker.ts");
const target = join(packageDir, "src", "builtin", "worker-source.ts");

const HEADER = `// GENERATED by scripts/gen-worker-source.ts from src/builtin/worker.ts and the
// checker modules it imports — do not edit by hand. Re-run that script after
// changing any of them; worker-source.test.ts fails until this text matches a
// fresh build.
/**
 * The builtin checker as one script, for a worker started from a Blob URL
 * (see ./runner for why it is text, not a file the worker loads).
 */
`;

async function bundle(): Promise<string> {
  const built = await Bun.build({
    entrypoints: [entry],
    target: "browser",
    format: "esm",
    minify: { whitespace: true, syntax: false, identifiers: false },
  });
  const [output] = built.outputs;
  if (!built.success || output === undefined || built.outputs.length !== 1) {
    throw new Error(`bundling ${entry} failed:\n${built.logs.map(String).join("\n")}`);
  }
  return output.text();
}

const source = await bundle();
if (process.argv.includes("--check")) {
  let current: unknown;
  try {
    current = ((await import(target)) as { BUILTIN_WORKER_SOURCE?: unknown }).BUILTIN_WORKER_SOURCE;
  } catch {
    // Missing or unreadable reads as stale.
  }
  if (current !== source) {
    console.error(
      `src/builtin/worker-source.ts is not a fresh build of src/builtin/worker.ts (bun ${Bun.version}); run: bun run scripts/gen-worker-source.ts`,
    );
    process.exit(1);
  }
  console.log(`src/builtin/worker-source.ts is current (${source.length} characters)`);
} else {
  writeFileSync(
    target,
    `${HEADER}export const BUILTIN_WORKER_SOURCE = ${JSON.stringify(source)};\n`,
  );
  // Biome formats this file like any other source file (it picks the quote
  // that needs fewer escapes), so format it here rather than leaving
  // `biome check` to fail on a fresh build.
  const fmt = Bun.spawnSync(["bunx", "biome", "format", "--write", target], { cwd: repoRoot });
  if (fmt.exitCode !== 0) {
    throw new Error(`biome format failed on ${target}: ${new TextDecoder().decode(fmt.stderr)}`);
  }
  console.log(`wrote src/builtin/worker-source.ts (${source.length} characters)`);
}
