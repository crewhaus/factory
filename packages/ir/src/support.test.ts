const declared = (feature: string) => [{ feature, path: feature }];

/** The same data, generated by a later release that moved `later`'s cell. */
const LATER: SupportManifest = { ...MANIFEST, generatedBy: "0.9.2" };

describe("parseRelease / compareReleases", () => {
  test("major.minor.patch, numerically; a pre-release of X counts as X", () => {
    expect(parseRelease("0.10.2")).toEqual([0, 10, 2]);
    expect(parseRelease("0.9.0-rc.1")).toEqual([0, 9, 0]);
    expect(parseRelease("v1.2.3")).toEqual([1, 2, 3]);
    expect(parseRelease("next")).toBeUndefined();
    expect(compareReleases("0.10.0", "0.9.9")).toBeGreaterThan(0);
    expect(compareReleases("0.9.0-rc.2", "0.9.0")).toBe(0);
    expect(compareReleases("0.8.4", "0.9.0")).toBeLessThan(0);
  });
});

describe("featureSupport", () => {
  test("a build older than the manifest reads unknown, with a note and the compile verb", () => {
    const support = featureSupport({
      shape: "managed",
      declared: declared("watchme"),
      compiledWith: "0.8.4",
      manifest: MANIFEST,
    });
    expect(support.basis).toBe("unknown");
    expect(support.note).toBe(
      "Built with CrewHaus 0.8.4. Recompile to check which settings take effect.",
    );
    expect(support.features).toEqual([
      {
        feature: "watchme",
        path: "watchme",
        status: "unknown",
        reason: support.note,
        verb: "crewhaus compile",
      },
    ]);
  });

  test("no build reads unknown, saying so", () => {
    const support = featureSupport({
      shape: "cli",
      declared: declared("watchme"),
      manifest: MANIFEST,
    });
    expect(support.basis).toBe("unknown");
    expect(support.note).toBe("This harness has no build yet.");
    expect(support.compiledWith).toBeUndefined();
    expect(support.features[0]?.status).toBe("unknown");
  });

  test("a build newer than the manifest reads unknown, and names no command", () => {
    const support = featureSupport({
      shape: "cli",
      declared: declared("watchme"),
      compiledWith: "0.10.0",
      manifest: MANIFEST,
    });
    expect(support.basis).toBe("unknown");
    expect(support.note).toBe(
      "Built with a newer CrewHaus (0.10.0) than this one (0.9.0). Update this CrewHaus to check which settings take effect.",
    );
    // Recompiling with the newer CrewHaus changes nothing this one can read.
    expect(support.verb).toBeUndefined();
    expect(support.features[0]).toEqual({
      feature: "watchme",
      path: "watchme",
      status: "unknown",
      reason: support.note,
    });
  });

  test("no build and an older build name crewhaus compile", () => {
    for (const compiledWith of [undefined, "0.8.4"]) {
      const support = featureSupport({
        shape: "cli",
        declared: declared("watchme"),
        ...(compiledWith !== undefined ? { compiledWith } : {}),
        manifest: MANIFEST,
      });
      expect(support.verb, String(compiledWith)).toBe("crewhaus compile");
      expect(support.features[0]?.verb, String(compiledWith)).toBe("crewhaus compile");
    }
  });

  test("a shape the manifest does not list reads unknown, never supported", () => {
    for (const shape of ["not-a-shape", "Managed", "managed ", "unknown", "voice@cf-worker"]) {
      const support = featureSupport({
        shape,
        declared: declared("watchme"),
        compiledWith: "0.9.0",
        manifest: MANIFEST,
      });
      expect(support.basis, shape).toBe("unknown");
      expect(support.verb, shape).toBeUndefined();
      expect(support.features, shape).toEqual([
        { feature: "watchme", path: "watchme", status: "unknown", reason: support.note },
      ]);
      expect(support.note, shape).toContain("does not know the");
    }
    // A declared cf-worker variant of a listed shape is known.
    const edge = featureSupport({
      shape: "cli@cf-worker",
      declared: declared("tenants"),
      compiledWith: "0.9.0",
      manifest: MANIFEST,
    });
    expect(edge.basis).toBe("manifest");
    expect(edge.features[0]?.status).toBe("unwired");
  });

  test("a cell the manifest does not hold reads unknown, and is never dropped", () => {
    const support = featureSupport({
      shape: "managed",
      declared: declared("later"),
      compiledWith: "0.9.0",
      manifest: MANIFEST,
    });
    expect(support.basis).toBe("manifest");
    expect(support.features).toEqual([
      {
        feature: "later",
        path: "later",
        status: "unknown",
        reason:
          "This version of CrewHaus has no record of what this setting does on managed harnesses.",
      },
    ]);
  });

  test("a key the shape's structure requires reads wired", () => {
    const support = featureSupport({
      shape: "managed",
      declared: declared("tenants"),
      compiledWith: "0.9.0",
      manifest: MANIFEST,
    });
    expect(support.features).toEqual([{ feature: "tenants", path: "tenants", status: "wired" }]);
  });

  test("a readable build reads each cell's status and reason", () => {
    const support = featureSupport({
      shape: "managed",
      declared: [...declared("watchme"), ...declared("intent")],
      compiledWith: "0.9.0",
      manifest: MANIFEST,
    });
    expect(support.basis).toBe("manifest");
    expect(support.note).toBeUndefined();
    expect(support.features).toEqual([
      {
        feature: "watchme",
        path: "watchme",
        status: "unwired",
        reason: "managed harnesses do not record demonstrations yet",
      },
      { feature: "intent", path: "intent", status: "authoring" },
    ]);
  });

  test("a cell that took effect after the build reads recompile", () => {
    const support = featureSupport({
      shape: "cli",
      declared: declared("later"),
      compiledWith: "0.9.1",
      manifest: LATER,
    });
    expect(support.features).toEqual([
      {
        feature: "later",
        path: "later",
        status: "recompile",
        reason: "Recompile to turn this on.",
        verb: "crewhaus compile",
      },
    ]);
  });

  test("a feature the manifest does not know reads unknown", () => {
    const support = featureSupport({
      shape: "cli",
      declared: declared("people"),
      compiledWith: "0.9.0",
      manifest: MANIFEST,
    });
    expect(support.features[0]?.status).toBe("unknown");
    expect(support.features[0]?.reason).toContain("does not know");
  });

  test("a pre-release of the manifest's release reads the manifest", () => {
    const support = featureSupport({
      shape: "cli",
      declared: declared("watchme"),
      compiledWith: "0.9.0-rc.1",
      manifest: MANIFEST,
    });
    expect(support.basis).toBe("manifest");
    expect(support.features[0]?.status).toBe("wired");
  });
});

describe("supportDescriptor", () => {
  const at = (feature: string, shape: string, compiledWith?: string) =>
    supportDescriptor({
      feature,
      shape,
      manifest: MANIFEST,
      ...(compiledWith !== undefined ? { compiledWith } : {}),
    });

  test("wired, degraded and authoring are supported", () => {
    expect(at("watchme", "cli", "0.9.0")).toEqual({ supported: true });
    expect(at("plugins", "cli", "0.9.0")).toEqual({ supported: true });
    expect(at("intent", "cli", "0.9.0")).toEqual({ supported: true });
  });

  test("unwired and rejected are not, with their reason and no command", () => {
    expect(at("watchme", "managed", "0.9.0")).toEqual({
      supported: false,
      reason: "managed harnesses do not record demonstrations yet",
      verb: null,
    });
    expect(at("plugins", "managed", "0.9.0")).toEqual({
      supported: false,
      reason: "not accepted",
      verb: null,
    });
  });

  test("recompile is not supported, with crewhaus compile", () => {
    expect(
      supportDescriptor({ feature: "later", shape: "cli", compiledWith: "0.9.1", manifest: LATER }),
    ).toEqual({
      supported: false,
      reason: "Recompile to turn this on.",
      verb: "crewhaus compile",
    });
  });

  test("an unknown shape and a missing cell are unknown, never supported", () => {
    expect(at("watchme", "not-a-shape", "0.9.0")).toEqual({
      supported: "unknown",
      reason:
        'This version of CrewHaus does not know the "not-a-shape" shape, so it cannot check which settings take effect.',
    });
    expect(at("later", "managed", "0.9.0")).toEqual({
      supported: "unknown",
      reason:
        "This version of CrewHaus has no record of what this setting does on managed harnesses.",
    });
    expect(at("tenants", "managed", "0.9.0")).toEqual({ supported: true });
  });

  test("unknown stays unknown, never unsupported", () => {
    expect(at("watchme", "managed", "0.8.4")).toEqual({
      supported: "unknown",
      reason: "Built with CrewHaus 0.8.4. Recompile to check which settings take effect.",
    });
    expect(at("watchme", "managed")).toEqual({
      supported: "unknown",
      reason: "This harness has no build yet.",
    });
  });
});

describe("declaredFeatures", () => {
  const features = (spec: unknown) =>
    declaredFeatures(spec, MANIFEST).map((d) => `${d.feature}@${d.path}`);

  test("a declared block is listed at its path", () => {
    expect(features({ watchme: { enabled: true }, plugins: ["a"] })).toEqual([
      "watchme@watchme",
      "plugins@plugins",
    ]);
  });

  test("false, enabled: false and empty values declare nothing", () => {
    expect(features({ watchme: false, plugins: [] })).toEqual([]);
    expect(features({ watchme: { enabled: false } })).toEqual([]);
    expect(features({ watchme: {} })).toEqual([]);
    expect(features({ memory: { enabled: false, wiki: { enabled: true } } })).toEqual([]);
    expect(features({ memory: { wiki: { enabled: false } } })).toEqual([]);
    expect(features({ memory: { wiki: { enabled: true } } })).toEqual(["memory.wiki@memory.wiki"]);
  });

  test("a provability block at level off declares nothing", () => {
    expect(features({ provability: "off" })).toEqual([]);
    expect(features({ provability: { level: "off", threshold: 1 } })).toEqual([]);
    expect(features({ provability: "cited" })).toEqual(["provability@provability"]);
  });

  test("* walks every list item and every key, once per concrete path", () => {
    const spec = {
      agent: { model_pool: { strategy: { cascade: { draft: "a", escalate_to: "b" } } } },
      steps: [
        { name: "a", model_pool: { strategy: { cascade: { draft: "a", escalate_to: "b" } } } },
        { name: "b" },
        { name: "c", model_pool: { strategy: { cascade: { draft: "a", escalate_to: "b" } } } },
      ],
    };
    expect(features(spec)).toEqual([
      "model_pool.strategy.cascade@agent.model_pool.strategy.cascade",
      "model_pool.strategy.cascade@steps[0].model_pool.strategy.cascade",
      "model_pool.strategy.cascade@steps[2].model_pool.strategy.cascade",
    ]);
  });

  test("anything but a mapping declares nothing", () => {
    expect(declaredFeatures(undefined, MANIFEST)).toEqual([]);
    expect(declaredFeatures("watchme: {}", MANIFEST)).toEqual([]);
    expect(declaredFeatures([{ watchme: {} }], MANIFEST)).toEqual([]);
  });
});

describe("the shipped manifest", () => {
  test("is schema 1, generated by a release line, with a cell per shape for compaction.curate", () => {
    expect(SUPPORT_MANIFEST.schema).toBe(1);
    expect(parseRelease(SUPPORT_MANIFEST.generatedBy)).toBeDefined();
    expect(SUPPORT_MANIFEST.shapes.length).toBe(14);
    const curate = SUPPORT_MANIFEST.features["compaction.curate"];
    expect(curate?.cells["cli"]?.status).toBe("wired");
    expect(curate?.cells["workflow"]?.status).toBe("unwired");
  });

  test("plugins.tools: a plugin's tool grant takes effect on cli, loads at start on channel, and is refused elsewhere", () => {
    const cells = SUPPORT_MANIFEST.features["plugins.tools"]?.cells ?? {};
    const status = (variant: string) => cells[variant]?.status;
    const descriptor = (shape: string) =>
      supportDescriptor({ feature: "plugins.tools", shape, compiledWith: "0.9.0" });
    expect(cells["cli"]).toMatchObject({ status: "wired", via: ["bundle"] });
    expect(descriptor("cli")).toEqual({ supported: true });
    expect(cells["channel"]).toMatchObject({
      status: "degraded",
      code: "channel-plugins-at-start",
    });
    expect(descriptor("channel")).toEqual({ supported: true });
    // A cli Worker build is refused at compile: the offline scope check cannot
    // verify the host tool the grant names.
    expect(status("cli@cf-worker")).toBe("rejected");
    expect(cells["cli@cf-worker"]?.reason).toContain('tool "Fetch"');
    expect(descriptor("cli@cf-worker")).toMatchObject({ supported: false, verb: null });
    const others = SUPPORT_MANIFEST.shapes.filter((s) => s !== "cli" && s !== "channel");
    for (const variant of [...others, "workflow@cf-worker", "graph@cf-worker"]) {
      expect(status(variant), variant).toBe("rejected");
    }
  });

  test("a Cloudflare Worker build's safety cells are refused or enforced, never unused", () => {
    const safety = /^(permissions|limits|budget|security|hooks)(\.|$)/;
    let checked = 0;
    for (const [feature, record] of Object.entries(SUPPORT_MANIFEST.features)) {
      if (!safety.test(feature)) continue;
      for (const shape of SUPPORT_MANIFEST.variants["cf-worker"]) {
        const cell = record.cells[`${shape}@cf-worker`];
        expect(cell, `${feature} on ${shape}@cf-worker`).toBeDefined();
        expect(["wired", "rejected"], `${feature} on ${shape}@cf-worker`).toContain(
          cell?.status as string,
        );
        checked += 1;
      }
    }
    expect(checked).toBeGreaterThan(60);
  });

  test("shapeCells lists one shape's cells in feature order", () => {
    const cells = shapeCells("managed", MANIFEST);
    expect(cells.map((c) => c.feature)).toEqual(["watchme", "plugins", "intent", "tenants"]);
  });
});

describe("the package's main entry does not load the manifest", () => {
  /** Every module `entry` reaches through relative imports. */
  function reach(entry: string, seen = new Set<string>()): Set<string> {
    if (seen.has(entry)) return seen;
    seen.add(entry);
    const source = readFileSync(entry, "utf8");
    for (const match of source.matchAll(/(?:import|export)[^"';]*from\s+["'](\.[^"']+)["']/g)) {
      const spec = match[1] as string;
      const base = resolve(dirname(entry), spec);
      const file = base.endsWith(".ts") ? base : `${base}.ts`;
      reach(file, seen);
    }
    return seen;
  }

  test("src/index.ts never reaches support.ts or support.generated.ts", () => {
    const files = [...reach(join(import.meta.dir, "index.ts"))].map((f) =>
      f.slice(import.meta.dir.length + 1),
    );
    expect(files).toContain("index.ts");
    expect(files.length).toBeGreaterThan(1);
    expect(files.filter((f) => f.startsWith("support"))).toEqual([]);
  });

  test("support.ts imports only its data", () => {
    const source = readFileSync(join(import.meta.dir, "support.ts"), "utf8");
    const specifiers = [...source.matchAll(/from\s+["']([^"']+)["']/g)].map((m) => m[1]);
    expect(specifiers).toEqual(["./support.generated"]);
  });
});
