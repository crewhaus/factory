describe("emitChannelBot — agent.ts", () => {
  test("uses singleTurn + resume for non-new turns and just singleTurn for first turn", () => {
    const c = fileMap(MIN_IR).get("agent.ts") ?? "";
    expect(c).toContain("singleTurn: true");
    expect(c).toContain("resume: { sessionId: args.sessionId }");
    // The seed now carries the boundary-classified inbound (__inbound), not
    // the raw args.message — see the Pillar-3 channel-boundary test below.
    expect(c).toContain('seedMessages: [{ role: "user", content: __inbound }]');
    expect(c).not.toContain('seedMessages: [{ role: "user", content: args.message }]');
    expect(c).toContain('sessionTarget: "channel"');
    expect(c).toContain('sessionName: "demo"');
  });

  test("classifies inbound channel text at the boundary before seeding the model (Pillar 3, FR-005)", () => {
    const c = fileMap(MIN_IR).get("agent.ts") ?? "";
    // Imports the channel boundary chokepoint.
    expect(c).toContain('import { classifyInbound } from "@crewhaus/channel-adapter-base";');
    // Calls it on the inbound message with the per-run runContext + channel origin.
    expect(c).toContain('classifyInbound(args.message, runContext, { origin: "channel" })');
    // The classify runs BEFORE the runChatLoop call (the redacted/tagged text
    // is what reaches the model), and its result feeds the seed.
    const classifyIdx = c.indexOf("classifyInbound(args.message");
    const loopIdx = c.indexOf("runChatLoop({");
    expect(classifyIdx).toBeGreaterThan(-1);
    expect(loopIdx).toBeGreaterThan(-1);
    expect(classifyIdx).toBeLessThan(loopIdx);
    expect(c).toContain("const __inbound = await classifyInbound(");
  });

  test("threads model + instructions + permissions from the IR", () => {
    const irPerm: IrChannelV0 = {
      ...MIN_IR,
      permissions: {
        mode: "auto",
        rules: [{ type: "alwaysAllow", pattern: "Read" }],
      },
    };
    const c = fileMap(irPerm).get("agent.ts") ?? "";
    expect(c).toContain('"claude-sonnet-4-6"');
    expect(c).toContain('"be helpful"');
    expect(c).toContain('permissionMode: "auto"');
    expect(c).toContain('pattern: "Read"');
    expect(c).toContain("BUILTIN_DEFAULT_RULES");
  });
});

describe("emitChannelBot — gateway.ts", () => {
  test("dedups by adapter-supplied idempotencyKey", () => {
    const c = fileMap(MIN_IR).get("gateway.ts") ?? "";
    expect(c).toContain("idempotencyKey");
    expect(c).toContain("dedup");
  });

  // SECURITY (audit R3): the dedup store is pluggable, the in-memory default
  // is behavior-preserving, and remember() is awaited (an unawaited Promise
  // is always truthy — every inbound event would be dropped as a duplicate).
  test("dedup runs through a pluggable DedupStore and remember() is awaited", () => {
    const c = fileMap(MIN_IR).get("gateway.ts") ?? "";
    expect(c).toContain('from "@crewhaus/durable-state"');
    expect(c).toContain("dedupStore?: DedupStore");
    expect(c).toContain("config.dedupStore ?? new InMemoryDedupStore");
    expect(c).toContain("await dedup.remember(parsed.event.idempotencyKey)");
  });

  test("daemon wires CREWHAUS_DEDUP_STORE through createDedupStore", () => {
    const c = fileMap(MIN_IR).get("daemon.ts") ?? "";
    expect(c).toContain('createDedupStore(process.env["CREWHAUS_DEDUP_STORE"] ?? "memory")');
    expect(c).toContain("dedupStore: __dedupStore");
  });

  test("returns 401 on signature mismatch", () => {
    const c = fileMap(MIN_IR).get("gateway.ts") ?? "";
    expect(c).toContain("status: 401");
    expect(c).toContain("invalid signature");
  });

  test("handles url_verification challenge with a plaintext body", () => {
    const c = fileMap(MIN_IR).get("gateway.ts") ?? "";
    expect(c).toContain('"text/plain"');
    expect(c).toContain("parsed.challenge");
  });

  test("matches /<adapter>/events path prefix", () => {
    const c = fileMap(MIN_IR).get("gateway.ts") ?? "";
    // The generated regex literal is /^\/([^/]+)\/events$/ — match the
    // /events$ tail to confirm the routing pattern is in place.
    expect(c).toContain("/events$/");
  });

  test("ACKs 200 immediately and dispatches the model turn asynchronously", () => {
    // Slack/Telegram/Discord/WhatsApp all expect a fast ACK on inbound
    // webhooks (Slack's documented bound is 3 s). Driving the model turn
    // synchronously would block the response and surface transient API
    // errors as 500s, prompting platform-side retries and duplicate work.
    // Confirm the generated handler dispatches the model call out-of-band
    // and never returns 500 from the inline handler path.
    const c = fileMap(MIN_IR).get("gateway.ts") ?? "";
    expect(c).toContain("queueMicrotask(");
    expect(c).toContain("config.sessionRouter.handle(parsed.event, adapter).catch");
    // The 500-on-handler-error branch from the prior synchronous-await
    // implementation should be gone. Any remaining `status: 500` in this
    // file would indicate a regression.
    expect(c).not.toContain("status: 500");
    expect(c).not.toContain('"handler error"');
  });
});

